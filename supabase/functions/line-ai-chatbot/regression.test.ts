import {needsWebSearch,cleanupSearchQuery,parseRss} from "./search.ts";
import {formatGroundedReply} from "./generation.ts";
import type {WebLookup} from "./search.ts";
import {safeEqual,verifyLine} from "./runtime.ts";
import {shouldRespond} from "./line.ts";

function check(ok:unknown,label:string):asserts ok {
 if(!ok)throw new Error("FAIL: "+label);
}
const weather:WebLookup={
 kind:"weather",status:"ok",provider:"wttr.in",
 context:"台北後天（11/20）預報：有雨，氣溫 14～16°C，最高降雨機率 64%。\n預報日期：2026-11-20",
 sources:[{title:"wttr.in 台北預報",url:"https://wttr.in/25.033,121.565?format=j1",snippet:"氣象預報"}],
 answer:"僅供檢查：舊版原始 API 模板"
};

Deno.test("search intent handles future-day weather",()=>{
 check(needsWebSearch("@BOT 後天台北天氣如何"),"future weather");
 check(needsWebSearch("最新台積電新聞"),"news");
 check(needsWebSearch("#搜尋 台北"),"manual search");
 check(!needsWebSearch("嗨今天吃什麼好呢"),"casual conversation should not search");
 check(cleanupSearchQuery("#搜尋 台北天氣")==="台北天氣","strip directive");
});

Deno.test("grounded answer keeps persona and a single trusted source footer",()=>{
 const response=formatGroundedReply("台北後天有雨耶，氣溫大概 14～16 度，出門記得帶傘喔！",weather);
 check(response.includes("有雨耶"),"natural response");
 check(response.includes("來源：wttr.in 台北預報 https://wttr.in/"),"source footer");
 check(response.indexOf("來源：")===response.lastIndexOf("來源："),"single footer");
 check(!response.includes("僅供檢查"),"never forward raw provider template");
});

Deno.test("outdated refusal is replaced with fact-grounded friendly answer",()=>{
 const response=formatGroundedReply("我沒辦法看即時天氣，請你自己 Google。",weather);
 check(response.includes("台北後天"),"location/day");
 check(response.includes("14～16"),"correct low/high");
 check(!response.includes("沒辦法"),"not an outdated refusal");
 check(response.includes("出門記得帶傘"),"natural weather guidance");
});

Deno.test("source URLs generated by model cannot override trusted citation",()=>{
 const response=formatGroundedReply("後天台北有雨，14～16 度，來源：https://wrong.example",weather);
 check(!response.includes("wrong.example"),"strip untrusted URL");
 check(response.includes("https://wttr.in/"),"only verified provider link");
});

Deno.test("RSS parser admits safe HTTPS links only",()=>{
 const xml='<rss><channel>'+
 '<item><title>新聞甲</title><link>https://example.com/news</link><description>內容</description></item>'+
 '<item><title>新聞乙</title><link>javascript:alert(1)</link><description>不安全</description></item>'+
 '</channel></rss>';
 const items=parseRss(xml);
 check(items.length===1&&items[0].title==="新聞甲","sanitize feed links");
});

Deno.test("group replies require explicit bot mention",async()=>{
 check(await shouldRespond({source:{type:"user"}}, ""), "direct message");
 check(!(await shouldRespond({source:{type:"group"},message:{type:"text"}}, "")), "unmentioned group");
 check(await shouldRespond({source:{type:"group"},message:{type:"text",mention:{mentionees:[{type:"user",isSelf:true}]}}}, ""), "bot mention");
});

Deno.test("signed webhook comparison rejects tampering",async()=>{
 const secret="test-only-do-not-use-in-production",body='{"events":[]}';
 const key=await crypto.subtle.importKey("raw",new TextEncoder().encode(secret),{name:"HMAC",hash:"SHA-256"},false,["sign"]);
 const signed=new Uint8Array(await crypto.subtle.sign("HMAC",key,new TextEncoder().encode(body)));
 const signature=btoa(String.fromCharCode(...signed));
 check(await verifyLine(secret,body,signature),"valid HMAC");
 check(!(await verifyLine(secret,body+"x",signature)),"invalid HMAC");
 check(safeEqual("abc","abc")&&!safeEqual("abc","abd"),"comparison");
});
